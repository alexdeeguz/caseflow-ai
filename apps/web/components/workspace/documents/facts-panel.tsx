'use client';

import { useEffect, useId, useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import {
  DocumentStatus,
  FactCategory,
  FactExtractionStatus,
  factCategoryLabels,
  factExtractionFailureMessages,
  type DocumentListItem,
  type ExtractedFact,
} from '@caseflow/schemas';
import type { AuthRequest } from '../../../hooks/use-authentication';
import { factsResource } from '../../../lib/fact-extraction/resources';
import { documentLibraryState } from '../../../lib/processing/resources';
import { resourceOptions } from '../../../lib/resources';
import { ApiError } from '../../../lib/api';
import { Pagination } from '../../ui/pagination';
import { FactExtractionBadge } from './fact-extraction-status';
import { DocumentDate } from './document-details';
import styles from './facts.module.css';

function FactCard({ fact }: { fact: ExtractedFact }) {
  const qualifiers = [
    fact.negated ? 'Negated' : null,
    fact.dateMeaning,
    fact.datePrecision,
    fact.treatmentStatus,
    fact.findingStatus,
    fact.qualifier,
  ].filter(Boolean);
  return (
    <li className={styles.fact}>
      <div className={styles.factHeader}>
        <span className={styles.category}>{factCategoryLabels[fact.category]}</span>
        <span className={styles.unreviewed}>Unreviewed</span>
      </div>
      <h4>{fact.value}</h4>
      {fact.dateValue && <p>{fact.dateValue}</p>}
      {qualifiers.length > 0 && <p className={styles.qualifiers}>{qualifiers.join(' · ')}</p>}
      {fact.evidence.map((evidence) => (
        <figure key={evidence.id} className={styles.evidence}>
          <figcaption>Source · Page {evidence.page}</figcaption>
          <blockquote>{evidence.quote}</blockquote>
        </figure>
      ))}
    </li>
  );
}

export function FactsPanel({
  document,
  request,
  onAccessRejected,
  onDownload,
  disabled,
}: {
  document: DocumentListItem;
  request: AuthRequest;
  onAccessRejected: (message: string) => void;
  onDownload: () => void;
  disabled: boolean;
}) {
  const [page, setPage] = useState(1);
  const [category, setCategory] = useState<FactCategory | undefined>();
  const id = useId();
  const summary = document.factExtraction;
  const available = document.status === DocumentStatus.Available;
  const completed = summary.status === FactExtractionStatus.Completed;
  const query = useQuery({
    ...resourceOptions(request, factsResource(document.caseId, document.id, page, category)),
    enabled: available && completed && !disabled,
    networkMode: 'online',
    refetchOnReconnect: 'always',
  });
  const state = documentLibraryState(query);
  const unavailable = query.error instanceof ApiError && query.error.status === 409;
  useEffect(() => {
    if (state.denied && state.error) {
      onAccessRejected(state.error);
    }
  }, [state.denied, state.error, onAccessRejected]);
  return (
    <section className={styles.panel} aria-labelledby={`${id}-heading`}>
      <header className={styles.heading}>
        <h3 id={`${id}-heading`}>Extracted facts</h3>
        <FactExtractionBadge summary={summary} />
      </header>
      <p className={styles.description}>
        Source-linked information generated by AI. Verify each fact against the original document
        before using it.
      </p>
      {summary.job?.finishedAt && (
        <p className={styles.description}>
          Last extraction: <DocumentDate value={summary.job.finishedAt} detailed />
        </p>
      )}
      {summary.job?.failureCode && (
        <p className={styles.failure}>{factExtractionFailureMessages[summary.job.failureCode]}</p>
      )}
      {!available ? (
        <p>Restore this document to view its facts.</p>
      ) : !completed ? (
        <p>
          {summary.status === FactExtractionStatus.NotExtracted
            ? 'An administrator can extract facts after text processing is ready.'
            : 'Facts become available when the complete extraction has finished.'}
        </p>
      ) : (
        <>
          <div className={styles.toolbar}>
            <label htmlFor={`${id}-category`}>Category</label>
            <select
              id={`${id}-category`}
              value={category ?? ''}
              onChange={(event) => {
                setCategory(event.target.value ? (event.target.value as FactCategory) : undefined);
                setPage(1);
              }}
            >
              <option value="">All categories</option>
              {Object.values(FactCategory).map((value) => (
                <option key={value} value={value}>
                  {factCategoryLabels[value]}
                </option>
              ))}
            </select>
            <button type="button" onClick={onDownload} disabled={disabled || !!state.error}>
              Download source
            </button>
          </div>
          {(state.stale || disabled) && state.data && (
            <p className={styles.notice}>
              Showing the last verified facts. Reconnect and refresh to confirm current access.
            </p>
          )}
          {state.denied || unavailable ? (
            <p role="alert">{state.error}</p>
          ) : state.data ? (
            <>
              {state.data.items.length ? (
                <ul className={styles.facts}>
                  {state.data.items.map((fact) => (
                    <FactCard key={fact.id} fact={fact} />
                  ))}
                </ul>
              ) : (
                <p>No facts in this category.</p>
              )}
              {(state.data.total > state.data.pageSize || page > 1) && (
                <Pagination {...state.data} onPage={setPage} />
              )}
            </>
          ) : (
            <p role={state.error ? 'alert' : 'status'}>{state.error ?? 'Loading facts…'}</p>
          )}
        </>
      )}
    </section>
  );
}
